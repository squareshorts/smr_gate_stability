def make_figure_6(root: Path) -> None:
    """Comparison: generic feedback vs Stuart-Landau vs SPT."""
    set_style()
    comp_df = load_csv("spt7_framework_comparison.csv")

    fig, axes = plt.subplots(1, 2, figsize=(11, 5))

    # Panel A: radar / heatmap of framework scores
    criteria_short = [
        "Empirical fit\n(mixed result)",
        "Non-diagnostic\nframing",
        "Testable\npredictions",
        "Mechanistic\nrichness",
        "Conservative\ncausal claims",
        "Separability\nsupport",
    ]
    # Assign scores: 0=lose, 1=draw, 2=win
    sl_scores = [0, 0, 1, 2, 0, 1]   # Stuart-Landau
    spt_scores = [2, 2, 2, 1, 2, 2]  # SPT

    x = np.arange(len(criteria_short))
    width = 0.35
    axes[0].bar(x - width / 2, sl_scores, width, label="Stuart-Landau", color="#ff7f0e",
                edgecolor="white", alpha=0.85)
    axes[0].bar(x + width / 2, spt_scores, width, label="SPT/Fast-slow", color="#2ca02c",
                edgecolor="white", alpha=0.85)
    axes[0].set_xticks(x)
    axes[0].set_xticklabels(criteria_short, fontsize=7)
    axes[0].set_yticks([0, 1, 2])
    axes[0].set_yticklabels(["Weak", "Partial", "Strong"])
    axes[0].set_title("(A) Framework comparison scores")
    axes[0].legend(fontsize=8)

    # Panel B: text table summary
    axes[1].axis("off")
    if not comp_df.empty:
        winners = comp_df["winner"].value_counts().to_dict()
        table_data = [
            ["SPT wins", str(winners.get("SPT", 0))],
            ["Stuart-Landau wins", str(winners.get("SL", 0))],
            ["Draw", str(winners.get("Draw", 0))],
            ["", ""],
            ["Recommendation", "DEMOTE SL"],
            ["", "to supplement"],
        ]
        table = axes[1].table(
            cellText=table_data,
            colLabels=["Criterion", "Count/Decision"],
            loc="center",
            cellLoc="left",
        )
        table.auto_set_font_size(False)
        table.set_fontsize(9)
        table.scale(1.3, 1.8)
    else:
        axes[1].text(0.5, 0.5, "SPT7 comparison\nnot run", ha="center", va="center",
                     transform=axes[1].transAxes, fontsize=11)
    axes[1].set_title("(B) Decision summary")

    fig.suptitle("Figure 6: Framework comparison – generic feedback, Stuart-Landau, SPT",
                 fontsize=10)
    plt.tight_layout()

    source = pd.DataFrame({
        "criterion": criteria_short,
        "sl_score": sl_scores,
        "spt_score": spt_scores,
    })
    save_csv_backed_figure(fig, source, "spt8_figure_6_framework_comparison", root)
    print("  spt8_figure_6 done")


