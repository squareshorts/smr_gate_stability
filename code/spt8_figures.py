# Figure 5: Barrier prediction (from SPT3 and SPT6)
# ---------------------------------------------------------------------------

def make_figure_5(root: Path) -> None:
    """Barrier violation prediction of next-state instability."""
    set_style()

    # SPT3 simulation barrier metrics
    barrier_df = load_csv("spt3_barrier_metrics.csv")
    # SPT6 empirical prediction
    pred_df = load_csv("spt6_barrier_prediction_models.csv")

    fig, axes = plt.subplots(1, 3, figsize=(13, 4.5))

    # Panel A: simulation - violation rate vs K_beta
    if not barrier_df.empty:
        for eps, grp in barrier_df.groupby("epsilon"):
            agg = grp.groupby("K_beta")["violation_rate"].mean()
            axes[0].plot(agg.index, agg.values, "o-", label=f"ε={eps}", lw=1.5)
        axes[0].set_xlabel("K_beta (barrier gain)")
        axes[0].set_ylabel("Violation rate")
        axes[0].set_title("(A) Simulation: barrier violation rate")
        axes[0].legend(fontsize=7)
    else:
        axes[0].text(0.5, 0.5, "SPT3 not run", ha="center", va="center",
                     transform=axes[0].transAxes)

    # Panel B: simulation - SMR change after violation vs admissible
    if not barrier_df.empty:
        agg_sim = barrier_df.groupby("K_beta")[["smr_change_after_viol", "smr_change_after_adm"]].mean()
        axes[1].plot(agg_sim.index, agg_sim["smr_change_after_viol"], "rs-",
                     lw=1.5, label="After violation")
        axes[1].plot(agg_sim.index, agg_sim["smr_change_after_adm"], "go-",
                     lw=1.5, label="After admissible")
        axes[1].axhline(0, color="black", ls="--", lw=0.8)
        axes[1].set_xlabel("K_beta")
        axes[1].set_ylabel("Next-block SMR change")
        axes[1].set_title("(B) SMR after barrier state (simulated)")
        axes[1].legend(fontsize=7)
    else:
        axes[1].text(0.5, 0.5, "SPT3 not run", ha="center", va="center",
                     transform=axes[1].transAxes)

    # Panel C: empirical prediction (if available)
    if not pred_df.empty and "threshold" in pred_df.columns and "perm_p" in pred_df.columns:
        sens = (
            pred_df.groupby(["threshold", "outcome"])
            .agg(mean_corr=("correlation", "mean"), mean_p=("perm_p", "mean"))
            .reset_index()
        )
        for outcome, grp in sens.groupby("outcome"):
            color = "#2ca02c" if "admissible" in outcome else "#1f77b4"
            axes[2].plot(range(len(grp)), grp["mean_corr"].values, "o-",
                         color=color, label=outcome.replace("_", " "), lw=1.5)
        axes[2].axhline(0, color="black", ls="--", lw=0.8)
        axes[2].set_xticks(range(len(grp)))
        axes[2].set_xticklabels([t.replace("viol_", "") for t in grp["threshold"].values],
                                rotation=30, ha="right")
        axes[2].set_xlabel("Violation threshold")
        axes[2].set_ylabel("Mean correlation (empirical)")
        axes[2].set_title("(C) Empirical violation → next state")
        axes[2].legend(fontsize=7)
    else:
        axes[2].text(0.5, 0.5,
                     "Empirical prediction\nnot available\n(SPT6 insufficient data)",
                     ha="center", va="center", transform=axes[2].transAxes,
                     fontsize=9, color="gray")
        axes[2].set_title("(C) Empirical violation → next state")

    fig.suptitle("Figure 5: Barrier violation and prediction of training instability", fontsize=10)
    plt.tight_layout()

    src = barrier_df if not barrier_df.empty else pd.DataFrame({"note": ["no data"]})
    save_csv_backed_figure(fig, src, "spt8_figure_5_barrier_prediction", root)
    print("  spt8_figure_5 done")


