# Figure 3: Time-scale separation and SPT validity (from SPT2)
# ---------------------------------------------------------------------------

def make_figure_3(root: Path) -> None:
    """Time-scale separation and boundary-layer validity."""
    set_style()
    ts_df = load_csv("spt2_timescale_metrics.csv")
    mf_df = load_csv("spt2_manifold_error.csv")

    fig, axes = plt.subplots(1, 3, figsize=(12, 4))

    if not ts_df.empty:
        eps_vals = sorted(ts_df["epsilon"].unique())
        tau_y = ts_df.groupby("epsilon")["tau_y_s"].mean()
        tau_x = ts_df.groupby("epsilon")["tau_x_s"].mean()
        tau_ratio = ts_df.groupby("epsilon")["tau_ratio"].mean()
        tau_ratio_std = ts_df.groupby("epsilon")["tau_ratio"].std()

        axes[0].loglog(eps_vals, [tau_y[e] for e in eps_vals],
                       "o-", color="#d62728", lw=1.5, label="τ_beta (fast)")
        axes[0].loglog(eps_vals, [tau_x[e] for e in eps_vals],
                       "s--", color="#2ca02c", lw=1.5, label="τ_SMR (slow)")
        axes[0].set_xlabel("ε (time-scale separation)")
        axes[0].set_ylabel("Time scale (s)")
        axes[0].set_title("(A) Time scales vs ε")
        axes[0].legend(fontsize=7)

        axes[1].errorbar(eps_vals,
                         [tau_ratio[e] for e in eps_vals],
                         yerr=[tau_ratio_std[e] for e in eps_vals],
                         fmt="ko-", lw=1.5, capsize=3)
        axes[1].axhline(0.1, color="green", ls="--", lw=0.8, label="SPT valid (ratio<0.1)")
        axes[1].axhline(0.2, color="orange", ls=":", lw=0.8, label="Partial (ratio<0.2)")
        axes[1].set_xscale("log")
        axes[1].set_xlabel("ε")
        axes[1].set_ylabel("τ_beta / τ_SMR")
        axes[1].set_title("(B) Time-scale ratio")
        axes[1].legend(fontsize=7)
    else:
        for ax in axes[:2]:
            ax.text(0.5, 0.5, "SPT2 not run", ha="center", va="center",
                    transform=ax.transAxes)

    if not mf_df.empty:
        err_mean = mf_df.groupby("epsilon")["mean_manifold_error"].mean()
        err_std = mf_df.groupby("epsilon")["mean_manifold_error"].std()
        eps_vals = sorted(mf_df["epsilon"].unique())
        axes[2].errorbar(eps_vals,
                         [err_mean[e] for e in eps_vals],
                         yerr=[err_std[e] for e in eps_vals],
                         fmt="ko-", lw=1.5, capsize=3)
        axes[2].set_xscale("log")
        axes[2].set_xlabel("ε")
        axes[2].set_ylabel("Mean |y - y_manifold|")
        axes[2].set_title("(C) Manifold approximation error")
    else:
        axes[2].text(0.5, 0.5, "SPT2 not run", ha="center", va="center",
                     transform=axes[2].transAxes)

    fig.suptitle("Figure 3: Singular perturbation validity – time-scale separation", fontsize=10)
    plt.tight_layout()

    src = ts_df[["epsilon", "tau_y_s", "tau_x_s", "tau_ratio", "spt_validity"]].copy() if not ts_df.empty else pd.DataFrame()
    save_csv_backed_figure(fig, src, "spt8_figure_3_timescale_separation", root)
    print("  spt8_figure_3 done")


