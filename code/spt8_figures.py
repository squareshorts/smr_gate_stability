# Figure 2: Separability simulation (from SPT1)
# ---------------------------------------------------------------------------

def make_figure_2(root: Path) -> None:
    """Simulation showing high-beta stabilization without SMR acquisition."""
    set_style()

    # Load SPT1 time series source (sample 4 regimes)
    src = load_csv("spt1_time_scale_separation_examples_source.csv")

    fig, axes = plt.subplots(2, 2, figsize=(10, 7))
    axes = axes.flatten()

    regime_labels = {
        "R1_stabilization_only": "R1: Stabilization only\n(beta↓, SMR→)",
        "R2_acquisition_only":   "R2: Acquisition only\n(SMR↑, beta→)",
        "R3_both":               "R3: Both\n(SMR↑, beta↓)",
        "R4_neither":            "R4: Neither\n(SMR→, beta→)",
    }
    regime_colors = {
        "R1_stabilization_only": "#1f77b4",
        "R2_acquisition_only":   "#ff7f0e",
        "R3_both":               "#2ca02c",
        "R4_neither":            "#d62728",
    }

    fig_source_rows = []

    for idx, (regime, label) in enumerate(regime_labels.items()):
        ax = axes[idx]
        if not src.empty and "regime" in src.columns:
            rdf = src[src["regime"] == regime].head(6000)
            if not rdf.empty:
                ax.plot(rdf["t"].values, rdf["x_smr"].values,
                        color="#2ca02c", lw=1.3, label="x (SMR)")
                ax.plot(rdf["t"].values, rdf["y_beta"].values,
                        color="#d62728", lw=1.0, alpha=0.85, label="y (High-beta)")
                for _, r in rdf.iterrows():
                    fig_source_rows.append({
                        "regime": regime, "t": r["t"],
                        "x_smr": r["x_smr"], "y_beta": r["y_beta"]
                    })
            else:
                ax.text(0.5, 0.5, f"{regime}\n(no data)", ha="center",
                        va="center", transform=ax.transAxes, fontsize=9)
        else:
            ax.text(0.5, 0.5, f"{regime}\n(SPT1 not run)", ha="center",
                    va="center", transform=ax.transAxes, fontsize=9)

        ax.axhline(0.5, color="black", ls="--", lw=0.8, label="Beta barrier" if idx == 0 else "_")
        ax.axhline(1.0, color="#2ca02c", ls=":", lw=0.8, label="SMR target" if idx == 0 else "_")
        ax.set_title(label, fontsize=9, color=regime_colors[regime])
        ax.set_xlabel("Time (s)")
        ax.set_ylabel("State")
        if idx == 0:
            ax.legend(fontsize=7, loc="upper right")

    fig.suptitle("Figure 2: Simulation separability – four regimes of fast-slow model",
                 fontsize=10)
    plt.tight_layout()

    src_out = pd.DataFrame(fig_source_rows) if fig_source_rows else pd.DataFrame({"regime": [], "t": [], "x_smr": [], "y_beta": []})
    save_csv_backed_figure(fig, src_out, "spt8_figure_2_separability_simulation", root)
    print("  spt8_figure_2 done")


