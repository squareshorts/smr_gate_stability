# Figure 1: Fast-slow model schematic (re-derived here for quality)
# ---------------------------------------------------------------------------

def make_figure_1(root: Path) -> None:
    """Conceptual diagram of the fast-slow closed-loop model."""
    set_style()
    fig = plt.figure(figsize=(8, 5))
    gs = gridspec.GridSpec(1, 2, width_ratios=[1.6, 1.0], figure=fig)

    ax_schema = fig.add_subplot(gs[0])
    ax_schema.set_xlim(0, 10)
    ax_schema.set_ylim(0, 8)
    ax_schema.axis("off")
    ax_schema.set_title("(A) Fast-slow model structure", loc="left", fontsize=9)

    def box(ax, x, y, w, h, label, color, alpha=0.18):
        rect = plt.Rectangle((x, y), w, h, linewidth=1.8, edgecolor=color,
                              facecolor=color, alpha=alpha, zorder=3)
        ax.add_patch(rect)
        ax.text(x + w / 2, y + h / 2, label, ha="center", va="center",
                fontsize=8, fontweight="bold", color=color, zorder=4,
                multialignment="center")

    box(ax_schema, 0.3, 5.2, 4.0, 2.2,
        "SLOW MANIFOLD\nx(t): SMR regulation\nlearning rate α_x\ndx/dt = f(x,y,u)", "#2ca02c")
    box(ax_schema, 0.3, 1.8, 4.0, 2.2,
        "FAST LAYER\ny(t): High-beta envelope\nstabilization rate β_y/ε\nε·dy/dt = g(x,y,u)", "#d62728")
    box(ax_schema, 5.8, 3.2, 3.8, 2.0,
        "CONTROLLER\nSMR reward: u_smr\nBarrier: h(y)=y_bar-y≥0\nInhibit: u_β=-K_β·viol(y)", "#1f77b4")

    # Arrows
    ap = dict(arrowstyle="-|>", color="#555555", lw=1.5)
    # x,y → controller
    ax_schema.annotate("", xy=(5.8, 4.8), xytext=(4.3, 6.3), arrowprops=ap)
    ax_schema.annotate("", xy=(5.8, 3.8), xytext=(4.3, 2.9), arrowprops=ap)
    # controller → x
    ax_schema.annotate("", xy=(4.3, 6.0), xytext=(9.6, 4.5),
                       arrowprops=dict(arrowstyle="-|>", color="#2ca02c", lw=1.5))
    # controller → y
    ax_schema.annotate("", xy=(4.3, 2.6), xytext=(9.6, 3.8),
                       arrowprops=dict(arrowstyle="-|>", color="#d62728", lw=1.5))
    # coupling x <-> y
    ax_schema.annotate("", xy=(2.3, 4.0), xytext=(2.3, 5.2),
                       arrowprops=dict(arrowstyle="<|-|>", color="#9467bd", lw=1.5))
    ax_schema.text(3.0, 4.6, "coupling\n(k_yx, k_xy)", fontsize=7, color="#9467bd",
                   ha="center", va="center")

    ax_schema.text(2.3, 1.3, "Fast: τ_y = ε/β_y  (seconds)", fontsize=8,
                   color="#d62728", ha="center")
    ax_schema.text(2.3, 7.7, "Slow: τ_x = 1/α_x  (seconds)", fontsize=8,
                   color="#2ca02c", ha="center")
    ax_schema.text(7.7, 2.5, "ε << 1\nfor SPT", fontsize=8,
                   ha="center", color="#1f77b4",
                   bbox=dict(boxstyle="round,pad=0.2", fc="lightblue", ec="#1f77b4", alpha=0.4))

    # Panel B: illustrative time series from SPT1 summary
    ax_ts = fig.add_subplot(gs[1])
    t = np.linspace(0, 120, 1200)
    rng = np.random.default_rng(42)
    # Stylized: slow x grows, fast y rapidly stabilizes
    x_demo = 1.0 - np.exp(-0.05 * t) + 0.05 * rng.standard_normal(len(t))
    y_demo = 0.3 + 0.3 * np.exp(-5.0 * t) + 0.08 * rng.standard_normal(len(t))
    y_demo = np.clip(y_demo, 0, 1)

    ax_ts.plot(t, x_demo, color="#2ca02c", lw=1.5, label="x (SMR, slow)")
    ax_ts.plot(t, y_demo, color="#d62728", lw=1.0, alpha=0.85, label="y (High-beta, fast)")
    ax_ts.axhline(0.5, color="black", ls="--", lw=0.8, label="Barrier threshold")
    ax_ts.set_xlabel("Time (s)")
    ax_ts.set_ylabel("State variable")
    ax_ts.set_title("(B) Illustrative dynamics", loc="left", fontsize=9)
    ax_ts.legend(fontsize=7, loc="center right")

    fig.suptitle("Figure 1: Fast-slow closed-loop neurofeedback model (SPT)", fontsize=10)
    plt.tight_layout()

    source = pd.DataFrame({"t": t, "x_smr_demo": x_demo, "y_beta_demo": y_demo})
    save_csv_backed_figure(fig, source, "spt8_figure_1_fast_slow_model", root)
    print("  spt8_figure_1 done")


